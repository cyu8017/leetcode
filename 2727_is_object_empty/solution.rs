// LeetCode 2727 - Is Object Empty
// https://leetcode.com/problems/is-object-empty/

use std::collections::HashMap;

impl Solution {
    pub fn is_empty(obj: HashMap<String, i32>) -> bool {
        obj.is_empty()
    }

    pub fn is_empty_vec(arr: Vec<i32>) -> bool {
        arr.is_empty()
    }
}
