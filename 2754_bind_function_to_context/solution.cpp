// LeetCode 2754 - Bind Function to Context
// https://leetcode.com/problems/bind-function-to-context/
// JS-only problem; C++ stand-in matching Go stub semantics.

#include <vector>

class Solution {
public:
    int bindFunction(int fn, std::vector<int>& args) {
        (void)args;
        return fn;
    }
};
